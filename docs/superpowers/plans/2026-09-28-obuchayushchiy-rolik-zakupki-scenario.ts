export type Rect = { x: number; y: number; w: number; h: number };

/** Строка анимированной сцены: выезжает по очереди, держится до конца сцены. */
export type Step = {
  text: string;
  /** true — строка набрана охрой: на ней держится внимание (ключевое правило). */
  accent?: boolean;
  /** Кадры от начала сцены, когда строка начинает выезжать. */
  delay: number;
};

export type Scene =
  | { kind: 'card'; title: string; note?: string; frames: number }
  | { kind: 'zoom'; shot: string; title: string; frames: number; focus: Rect }
  | { kind: 'steps'; title: string; frames: number; steps: Step[] };

