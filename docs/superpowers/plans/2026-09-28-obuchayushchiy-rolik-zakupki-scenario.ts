/** Σ frames по всем сценам. Проверка в scripts/check.mjs сверяет с композицией. */
export const ZAKUPKI_TOTAL_FRAMES = ZAKUPKI_SCENES.reduce(
  (sum, s) => sum + s.frames,
  0,
); // 3534

/** Длина композиции: кроссфейды 12 кадров считаются дважды, кроме первой сцены. */
export const ZAKUPKI_DURATION =
  ZAKUPKI_TOTAL_FRAMES - 12 * (ZAKUPKI_SCENES.length - 1); // 3390
