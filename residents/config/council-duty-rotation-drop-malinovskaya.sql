-- Анастасия Малиновская исключена из CouncilDutyRotation::ORDER (была поз. 4;
-- в очереди теперь 11 позиций, 0..10). Индексы за удалённой позицией сдвигаем
-- на -1, чтобы текущий дежурный и вся очередь не переменились: позиция i
-- старого списка (i > 4) = позиция i-1 нового. Например, действовавший на прод
-- rotation_index = 7 (Марина Людоговская) → 6 — та же Марина в новом списке.
-- Позиция 4 старого списка (сама А. Малиновская, если бы она дежурила) не
-- трогается: под новым списком поз. 4 = Максим Жулидов, следующий в очереди.
--
-- Накат — ТОЛЬКО системой миграций (deploy.sh с MIGRATE=1, до выкладки кода):
-- вручную через mysql НЕ запускать, повторный накат сдвинет индекс ещё раз.
UPDATE council_meeting
   SET rotation_index = rotation_index - 1
 WHERE id = 1 AND rotation_index > 4;
