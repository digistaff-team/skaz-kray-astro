/**
 * Часовой пояс приложения — Москва, UTC+3 (летнего времени в России нет с 2014 года).
 *
 * Сервер живёт в UTC, и раньше «сегодня» наступало в 03:00 по Москве: просрочка
 * возврата, «поездка прошла», конец сбора закупки переключались на три часа позже
 * полуночи, а «сохранено на …» на главной показывало время по UTC.
 *
 * Подключается первым делом везде, где есть PHP-время: веб (src/bootstrap.php),
 * консольные скрипты (bin/*.php) и тесты (tests/bootstrap.php). Сессию MySQL
 * Database::connect() переводит в тот же сдвиг — иначе DEFAULT CURRENT_TIMESTAMP
 * ставил бы время по UTC рядом с московским из PHP.
 *
 * Исключение — уровень воды: почасовые замеры хранятся по UTC (метка часа —
 * первичный ключ, повторная запись того же часа перезаписывает строку), и эта
 * подсистема работает с UTC явно: WaterLevelController, bin/water-level-snapshot.php,
 * WaterLevelImport::hourOf(), WaterLevel::mskTime().
 *
 * Старые записи в базе остались по UTC — на три часа «раньше» новых.
 */
